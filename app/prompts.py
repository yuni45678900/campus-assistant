# 查询改写：把口语化问题转成检索友好的查询
REWRITE_PROMPT = """你是一个检索查询改写器。请把用户的口语化提问改写成更适合检索的查询语句。

要求：
1. 补全省略和指代，把"它""这个""那里"还原成具体对象；
2. 口语表达转成书面表达（如"咋办"→"如何办理"）；
3. 保留原意，绝对不要添加用户没有提到的信息；
4. 如果原问题已经足够清晰，就原样输出；
5. 只输出改写后的查询，不要解释、不要加引号、不要加前缀。

用户提问：{question}
改写结果："""


def build_user_message(question: str, contexts: List[Dict]) -> str:
    """把检索到的片段拼成给模型的资料块 + 问题。"""
    if not contexts:
        ctx_text = "（无）"
    else:
        blocks = []
        for c in contexts:
            blocks.append(f"{c['header']}\n{c['text']}")
        ctx_text = "\n\n".join(blocks)

    return (
        "【参考资料】\n"
        f"{ctx_text}\n\n"
        "【问题】\n"
        f"{question}\n\n"
        "请严格依据上面的参考资料回答。如果资料中没有能回答本问题的内容，"
        "就明确说明\"现有资料未包含该信息\"，并省略来源行；"
        "能回答时，在回答末尾单独一行标注「来源：《这里写真实文件名.docx》」，"
        "书名号里换成你实际依据的那份资料的**真实文件名**（别写\"文件名\"三个字）。"
    )
